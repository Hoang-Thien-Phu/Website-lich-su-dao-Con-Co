(() => {
  const list = window.CON_CO_SCENARIOS || [];
  const $ = s => document.querySelector(s);
  let current = 0, score = 0, answered = false, details = [];
  function render() {
    if (current >= list.length) return finish();
    const item = list[current];
    answered = false;
    $('#scenarioCount').textContent = `TÌNH HUỐNG ${current + 1} / ${list.length}`;
    $('#scenarioBar').style.width = `${((current + 1) / list.length) * 100}%`;
    $('#scenarioScore').textContent = String(score).padStart(2, '0');
    $('#scenarioTitle').textContent = item.title;
    $('#scenarioText').textContent = item.text;
    $('#scenarioFeedback').textContent = '';
    $('#nextScenario').disabled = true;
    $('#nextScenario').textContent = current === list.length - 1 ? 'XEM KẾT QUẢ' : 'TIẾP TỤC →';
    $('#scenarioChoices').innerHTML = '';
    item.choices.forEach((choice, index) => {
      const button = document.createElement('button');
      button.type = 'button';
      button.className = 'scenario-choice';
      button.textContent = `${String.fromCharCode(65 + index)}. ${choice[0]}`;
      button.addEventListener('click', () => select(index));
      $('#scenarioChoices').appendChild(button);
    });
  }
  function select(index) {
    if (answered) return;
    answered = true;
    const item = list[current], picked = item.choices[index];
    score += picked[1];
    details.push(picked[1]);
    document.querySelectorAll('.scenario-choice').forEach((button, i) => {
      button.disabled = true;
      if (item.choices[i][1] === 2) button.classList.add('good');
      if (i === index && picked[1] === 0) button.classList.add('bad');
    });
    $('#scenarioFeedback').textContent =
      `${picked[1] === 2 ? 'Phù hợp nhất. ' : 'Chưa phù hợp. '}${picked[2]}`;
    $('#scenarioScore').textContent = String(score).padStart(2, '0');
    $('#nextScenario').disabled = false;
  }
  function finish() {
    $('#scenarioCount').textContent = 'HOÀN THÀNH';
    $('#scenarioBar').style.width = '100%';
    $('#scenarioScore').textContent = String(score).padStart(2, '0');
    $('#scenarioTitle').textContent = 'Bạn đã hoàn thành thử thách!';
    $('#scenarioText').textContent = `Tổng điểm: ${score}/14.`;
    $('#scenarioChoices').innerHTML = '';
    let label = score >= 10 ? 'Nhà quản lý đảo xanh' :
      score >= 6 ? 'Người bảo vệ tiềm năng' : 'Hãy khám phá lại Cồn Cỏ và thử lần nữa';
    $('#scenarioFeedback').textContent = label;
    $('#nextScenario').hidden = true;
  }
  $('#nextScenario')?.addEventListener('click', () => {
    if (!answered) return;
    current += 1;
    render();
  });
  render();
})();
